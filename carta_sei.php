<h2 style="color: rgb(161, 243, 252);">L'intruso</h2>

<p>L'Intruso è il corpo celeste più recente del sistema solare di Outer Wilds, una cometa di piccole dimensioni caratterizzata da un'orbita altamente ellittica che la costringe a passaggi estremamente ravvicinati al Sole. Questa traiettoria ciclica influisce direttamente sulla sua struttura superficiale, mentre al suo interno l'esplorazione è guidata da una totale assenza di gravità.</p>

