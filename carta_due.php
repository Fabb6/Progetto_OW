<h2 style="color: brown">Cuore legnoso</h2>

<p>Cuore Legnoso è il pianeta natale dei Teporiani: accogliente, rigoglioso e caratterizzato da fitte foreste di pini, fiumi, geyser e grandi crateri montuosi che ospitano il villaggio principale della specie.
Dietro la sua apparenza tranquilla e rurale, il pianeta nasconde importanti misteri sotterranei e scientifici.</p>

