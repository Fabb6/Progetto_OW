<h2 style="color: rgba(119, 109, 101, 0.79);">Rovo oscuro</h2>

<p>Rovo oscuro è una vasta e intricata rete di viticci contorti e passaggi di teletrasporto; si tratta dei resti implosi di un quinto pianeta, da tempo invaso e sopraffatto da una vegetazione capace di distorcere lo spazio. È l'unico pianeta a ospitare una fauna ostile, rappresentata dai pesci rana (Anglerfish).</p>

