<h2 style="color: rgba(187, 13, 42, 0.73);">Vuoto fragile</h2>

<p>Vuoto fragile è il terzo pianeta del sistema solare: è costituito da una crosta rocciosa e fragile che racchiude un interno cavo, al cui centro si trova un grande buco nero che funge da nucleo. I continui bombardamenti provenienti dalla luna del pianeta causano il distacco di frammenti della crosta, che precipitano poi nel buco nero centrale.</p>

